-- Medicine Inventory Management - database schema + sample data (MySQL 8)
-- Run this once in MySQL Workbench / mysql CLI. Re-running it RESETS the data.
-- Sample dates are relative to today, so the dashboard always has fresh alerts.

CREATE DATABASE IF NOT EXISTS medicine_inventory;
USE medicine_inventory;

DROP TABLE IF EXISTS stock_transactions;
DROP TABLE IF EXISTS batches;
DROP TABLE IF EXISTS suppliers;
DROP TABLE IF EXISTS medicines;

CREATE TABLE medicines (
  id            BIGINT AUTO_INCREMENT PRIMARY KEY,
  name          VARCHAR(255) NOT NULL UNIQUE,
  category      VARCHAR(255),
  unit          VARCHAR(255),
  reorder_level INT NOT NULL DEFAULT 0,
  unit_price    DECIMAL(10,2) NOT NULL
);

CREATE TABLE suppliers (
  id             BIGINT AUTO_INCREMENT PRIMARY KEY,
  name           VARCHAR(255) NOT NULL,
  contact_person VARCHAR(255),
  phone          VARCHAR(255),
  email          VARCHAR(255),
  address        VARCHAR(255)
);

CREATE TABLE batches (
  id               BIGINT AUTO_INCREMENT PRIMARY KEY,
  batch_number     VARCHAR(255) NOT NULL,
  medicine_id      BIGINT NOT NULL,
  supplier_id      BIGINT,
  manufacture_date DATE,
  expiry_date      DATE NOT NULL,
  quantity         INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_batch_medicine FOREIGN KEY (medicine_id) REFERENCES medicines(id),
  CONSTRAINT fk_batch_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
  CONSTRAINT uq_batch UNIQUE (medicine_id, batch_number),
  INDEX idx_batch_expiry (expiry_date)
);

CREATE TABLE stock_transactions (
  id         BIGINT AUTO_INCREMENT PRIMARY KEY,
  batch_id   BIGINT NOT NULL,
  txn_type   VARCHAR(20) NOT NULL,          -- PURCHASE, ISSUE, RETURN, WRITE_OFF
  quantity   INT NOT NULL,                  -- always positive
  note       VARCHAR(255),
  created_at DATETIME NOT NULL,
  CONSTRAINT fk_txn_batch FOREIGN KEY (batch_id) REFERENCES batches(id),
  INDEX idx_txn_type_date (txn_type, created_at)
);

